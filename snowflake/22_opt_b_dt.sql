-- Option B silver Dynamic Table: plain casts, no UDF, no external call.
USE ROLE PK_PIPELINE;
USE WAREHOUSE PK_WH;
CREATE OR REPLACE DYNAMIC TABLE PII_KEY_DEMO.OPT_B.SILVER
  TARGET_LAG = '1 minute' WAREHOUSE = PK_WH REFRESH_MODE = INCREMENTAL
AS
SELECT RECORD:patient_id::INT        AS patient_id,
       RECORD:event_ts::TIMESTAMP_TZ AS event_ts,
       RECORD:event_type::STRING     AS event_type,
       RECORD:email::STRING          AS email,
       RECORD:full_name::STRING      AS full_name,
       RECORD:email_kid::STRING      AS key_id,
       LOADED_AT
FROM PII_KEY_DEMO.OPT_B.BRONZE_PLAIN;

USE ROLE ACCOUNTADMIN;
ALTER DYNAMIC TABLE PII_KEY_DEMO.OPT_B.SILVER MODIFY COLUMN EMAIL SET TAG PII_KEY_DEMO.COMMON.PHI = 'email';
ALTER DYNAMIC TABLE PII_KEY_DEMO.OPT_B.SILVER MODIFY COLUMN FULL_NAME SET TAG PII_KEY_DEMO.COMMON.PHI = 'name';
