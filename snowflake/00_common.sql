-- Common objects: database, warehouse, roles and tag-based PHI masking.
-- Variables: &{demo_user}
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS PII_KEY_DEMO;
CREATE SCHEMA IF NOT EXISTS PII_KEY_DEMO.COMMON;
CREATE SCHEMA IF NOT EXISTS PII_KEY_DEMO.OPT_A;
CREATE SCHEMA IF NOT EXISTS PII_KEY_DEMO.OPT_B;
CREATE WAREHOUSE IF NOT EXISTS PK_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;

-- PK_PIPELINE owns the Dynamic Tables. It gets USAGE on the decrypt UDF only: no secret, no integration.
-- PK_PHI_READER sees PHI in clear. PK_ANALYST sees it masked.
CREATE ROLE IF NOT EXISTS PK_PIPELINE;
CREATE ROLE IF NOT EXISTS PK_PHI_READER;
CREATE ROLE IF NOT EXISTS PK_ANALYST;
GRANT ROLE PK_PIPELINE TO ROLE SYSADMIN;
GRANT ROLE PK_PHI_READER TO ROLE SYSADMIN;
GRANT ROLE PK_ANALYST TO ROLE SYSADMIN;
GRANT ROLE PK_PIPELINE TO USER IDENTIFIER('&{demo_user}');
GRANT ROLE PK_PHI_READER TO USER IDENTIFIER('&{demo_user}');
GRANT ROLE PK_ANALYST TO USER IDENTIFIER('&{demo_user}');

GRANT USAGE ON WAREHOUSE PK_WH TO ROLE PK_PIPELINE;
GRANT USAGE ON WAREHOUSE PK_WH TO ROLE PK_PHI_READER;
GRANT USAGE ON WAREHOUSE PK_WH TO ROLE PK_ANALYST;
GRANT USAGE ON DATABASE PII_KEY_DEMO TO ROLE PK_PIPELINE;
GRANT USAGE ON DATABASE PII_KEY_DEMO TO ROLE PK_PHI_READER;
GRANT USAGE ON DATABASE PII_KEY_DEMO TO ROLE PK_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PII_KEY_DEMO TO ROLE PK_PIPELINE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PII_KEY_DEMO TO ROLE PK_PHI_READER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PII_KEY_DEMO TO ROLE PK_ANALYST;
GRANT CREATE DYNAMIC TABLE ON SCHEMA PII_KEY_DEMO.OPT_A TO ROLE PK_PIPELINE;
GRANT CREATE DYNAMIC TABLE ON SCHEMA PII_KEY_DEMO.OPT_B TO ROLE PK_PIPELINE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA PII_KEY_DEMO.OPT_A TO ROLE PK_PHI_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA PII_KEY_DEMO.OPT_A TO ROLE PK_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA PII_KEY_DEMO.OPT_B TO ROLE PK_PHI_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA PII_KEY_DEMO.OPT_B TO ROLE PK_ANALYST;

-- PHI tag with one masking policy per data type. PK_PIPELINE is exempt so a Dynamic Table can read
-- tagged base columns (Option B bronze) and materialize real values; readers of the DT are masked again.
CREATE TAG IF NOT EXISTS PII_KEY_DEMO.COMMON.PHI COMMENT = 'Protected health information';
CREATE MASKING POLICY IF NOT EXISTS PII_KEY_DEMO.COMMON.MASK_PHI_STRING AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('PK_PHI_READER') OR CURRENT_ROLE() = 'PK_PIPELINE' THEN v ELSE '***PHI***' END;
CREATE MASKING POLICY IF NOT EXISTS PII_KEY_DEMO.COMMON.MASK_PHI_VARIANT AS (v VARIANT) RETURNS VARIANT ->
  CASE WHEN IS_ROLE_IN_SESSION('PK_PHI_READER') OR CURRENT_ROLE() = 'PK_PIPELINE' THEN v
       ELSE TO_VARIANT('***PHI***') END;
ALTER TAG PII_KEY_DEMO.COMMON.PHI SET MASKING POLICY PII_KEY_DEMO.COMMON.MASK_PHI_STRING,
                                         MASKING POLICY PII_KEY_DEMO.COMMON.MASK_PHI_VARIANT;
